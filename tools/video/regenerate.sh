#!/usr/bin/env bash
# Regenerate everything under docs/video/ and docs/howto/img/ from the scripts (docs/video/README.md).
#
#   tools/video/regenerate.sh               # build (submission mode), capture all shots, how-to screenshots, previews
#   tools/video/regenerate.sh --skip-build  # reuse apps/web/out-e2e
#   tools/video/regenerate.sh --only judges-04,clip-03   # re-capture some shots or sequences, then re-assemble
#
# Needs: Node 22.18+ with apps/web's dependencies (pnpm install), the runtime's Python env (uv sync --all-packages,
# or E2E_PYTHON), ffmpeg with libass and libvpx. Nothing here contacts Meta, Microsoft or HMRC: the runtime runs in
# test mode with the demo sandbox (fictional sample books).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"
CAPTURE_ARGS=()
ONLY=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --skip-build) CAPTURE_ARGS+=(--skip-build) ;;
    --only) ONLY="$2"; CAPTURE_ARGS+=(--only "$2"); shift ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
  shift
done

node tools/video/capture.ts "${CAPTURE_ARGS[@]}"
[[ -z "$ONLY" ]] && node tools/video/howto.ts
python3 tools/video/vo.py lines
tools/video/assemble.sh

# Raw shots over 5 MB stay out of git (listed here); smaller ones are committed so the Spark can assemble without
# re-capturing.
{
  echo "# Generated by tools/video/regenerate.sh: raw shots over 5 MB (regenerate them, do not commit)."
  find docs/video/raw -name '*.webm' -size +5M -printf '%f\n' | sort
} > docs/video/raw/.gitignore
echo "raw shots over 5 MB: $(($(wc -l < docs/video/raw/.gitignore) - 1))"
