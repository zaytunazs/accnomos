"""Write the books folder layout from services/runtime/app/paths.py to the files the other apps read.

    python tools/gen_folders.py           rewrite them
    python tools/gen_folders.py --check   exit 1 if any of them is out of date (services/runtime/tests/test_paths.py)

Outputs:
    packages/connectors/folders.json      the shared fixture: top folders, full tree, old names, README.txt text
    apps/web/src/lib/folders.ts           the whole file
    apps/mobile/lib/services/graph.dart   only the block between the BEGIN/END markers
Each carries the tree as the same JSON array text, so the three lists are byte for byte equal.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "services/runtime") not in sys.path:
    sys.path.insert(0, str(ROOT / "services/runtime"))

from app import paths  # noqa: E402

JSON_FILE = ROOT / "packages/connectors/folders.json"
TS_FILE = ROOT / "apps/web/src/lib/folders.ts"
DART_FILE = ROOT / "apps/mobile/lib/services/graph.dart"
DART_BEGIN = "// BEGIN books folders"
DART_END = "// END books folders"
SOURCE = "services/runtime/app/paths.py"


def _s(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def tree_text() -> str:
    """The canonical bytes of the folder list, as it appears in all three files."""
    return _s(list(paths.TREE))


def fixture() -> str:
    data = {
        "source": SOURCE,
        "top": [f._asdict() for f in paths.TOP],
        "tree": list(paths.TREE),
        "renamed": paths.RENAMED,
        "readme": paths.readme_text(),
    }
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def typescript() -> str:
    readme = paths.readme_text()
    if re.search(r"[`\\]|\$\{", readme):
        raise ValueError("README text cannot go in a template literal as is")
    top = "\n".join(f"  {{ key: {_s(f.key)}, name: {_s(f.name)}, note: {_s(f.note)} }}," for f in paths.TOP)
    keys = "\n".join(f"  {f.key}: {_s(f.name)}," for f in paths.TOP)
    renamed = "\n".join(f"  {_s(old)}: {_s(new)}," for old, new in paths.RENAMED.items())
    return f"""// Generated by tools/gen_folders.py from {SOURCE}. Do not edit: change paths.py and run
// `python tools/gen_folders.py`. services/runtime/tests/test_paths.py checks that this file is up to date.

/** Every folder in the books tree, in the order it is created. Personal accounts: OneDrive app folder
 * (Apps/Accnomos). Work accounts: /Accnomos in the root. */
export const FOLDERS: readonly string[] = {tree_text()};

/** The top-level folders, with the line README.txt shows for each. */
export const TOP_FOLDERS: readonly {{ key: string; name: string; note: string }}[] = [
{top}
];

/** Top-level folder names by key. */
export const FOLDER = {{
{keys}
}} as const;

/** Old folder name -> current name. The runtime moves an old-named folder once (services/runtime/app/layout.py). */
export const RENAMED: Readonly<Record<string, string>> = {{
{renamed}
}};

export const README_TEXT = `{readme}`;
"""


def dart_block() -> str:
    return f"""{DART_BEGIN}: generated by tools/gen_folders.py from {SOURCE}. Do not edit.
/// Every folder in the books tree, in order (the same list as the runtime and the web app).
const List<String> kBooksFolders = {tree_text()};
{DART_END}"""


def dart(current: str) -> str:
    pattern = re.compile(re.escape(DART_BEGIN) + r".*?" + re.escape(DART_END), re.S)
    if not pattern.search(current):
        raise ValueError(f"{DART_FILE} has no {DART_BEGIN} ... {DART_END} block")
    return pattern.sub(lambda _: dart_block(), current, count=1)


def render() -> dict[Path, str]:
    return {
        JSON_FILE: fixture(),
        TS_FILE: typescript(),
        DART_FILE: dart(DART_FILE.read_text(encoding="utf-8")),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report files that are out of date")
    args = ap.parse_args()
    stale = []
    for path, text in render().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.write_text(text, encoding="utf-8")
    for p in stale:
        print(f"{'out of date' if args.check else 'wrote'}: {p}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
