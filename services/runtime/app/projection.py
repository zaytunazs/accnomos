GBP = '"£"#,##0.00;-"£"#,##0.00'
WHOLE_GBP = '"£"#,##0;-"£"#,##0'
DATE = "dd/mm/yyyy"
SAMPLE_LABEL = "SAMPLE — FICTIONAL COMPANY"
SHEETS = ("README", "Summary", "Ledger", "Accounts", "VAT", "Suppliers", "Bank", "Proposals", "Vehicles")
GENERATED_NOTE = "This file is generated by Accnomos from the ledger event files in _System/Ledger/events. Do not edit it: changes are overwritten at the next rebuild; change things in the app."
VAT_BOXES = (
    (1, "VAT due on sales"), (2, "VAT due on acquisitions from NI/EU"), (3, "Total VAT due"),
    (4, "VAT reclaimed on purchases"), (5, "Net VAT to pay or reclaim"), (6, "Total sales ex VAT"),
    (7, "Total purchases ex VAT"), (8, "Goods supplied to NI/EU"), (9, "Goods acquired from NI/EU"),
)


def pounds(pence: int | None) -> float | None:
    return None if pence is None else pence / 100


def _table(ws: Worksheet, header: Sequence[str], rows: Iterable[Sequence[object]],
           money: Sequence[int] = (), dates: Sequence[int] = (), widths: Sequence[int] = ()) -> None:
    """Bold header, frozen below it, money/date number formats on the given (1-based) columns."""
    ws.append(list(header))
    for cell in ws[1]:
        cell.font = Font(bold=True)
    for row in rows:
        ws.append(list(row))
    for col in money:
        for (cell,) in ws.iter_rows(min_row=2, min_col=col, max_col=col):
            cell.number_format = GBP
    for col in dates:
        for (cell,) in ws.iter_rows(min_row=2, min_col=col, max_col=col):
            cell.number_format = DATE
    for i, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = width
    ws.freeze_panes = "A2"


def _read_me(ws: Worksheet, generated: datetime) -> None:
    rows = [
        ("Accnomos books", ""),
        (GENERATED_NOTE, ""),
        ("Generated at", generated.strftime("%d/%m/%Y %H:%M UTC")),
        (SAMPLE_LABEL, "Demo books are fictional; real books show your own entries only."),
        ("", ""),
        ("Sheet", "What it shows"),
        ("Summary", "Totals: entries posted, sales, purchases, VAT, bank matching and open proposals."),
        ("Ledger", "Every line of every approved ledger entry (double entry, £), with a totals row."),
        ("Accounts", "Trial balance: total debits, credits and balance per account."),
        ("VAT", "The 9 VAT return boxes for the last 4 complete quarters, computed by code."),
        ("Suppliers", "Approved purchases per supplier: entries, net, VAT and gross (£)."),
        ("Bank", "Imported bank statement lines and the ledger entries they are matched to."),
        ("Proposals", "Documents read by the AI that are still waiting for your decision."),
        ("Vehicles", "Business miles, approved mileage allowance and tagged running costs per vehicle, this tax year."),
    ]
    for row in rows:
        ws.append(list(row))
    for r in (1, 2, 6):
        ws.cell(row=r, column=1).font = Font(bold=True)
    ws.cell(row=6, column=2).font = Font(bold=True)
    ws.column_dimensions["A"].width = 34
    ws.column_dimensions["B"].width = 80
    ws.freeze_panes = "A2"


def _ledger(ws: Worksheet, events: Sequence[LedgerEvent]) -> None:
    rows = [
        (e.date, e.id, ln.account, pounds(ln.debit) or None, pounds(ln.credit) or None,
         ln.vat_code.value if ln.vat_code else None, e.counterparty, ", ".join(e.evidence) or None)
        for e in events for ln in e.lines
    ]
    debits = sum(ln.debit for e in events for ln in e.lines)
    credits = sum(ln.credit for e in events for ln in e.lines)
    rows.append((None, "Total", None, pounds(debits), pounds(credits), None, None, None))
    header = ("Date", "Event id", "Account", "Debit £", "Credit £", "VAT code", "Counterparty", "Evidence doc")
    _table(ws, header, rows, money=(4, 5), dates=(1,), widths=(12, 34, 32, 12, 12, 9, 28, 66))
    ws.cell(row=ws.max_row, column=2).font = Font(bold=True)


def trial_balance(events: Iterable[LedgerEvent]) -> list[tuple[str, int, int]]:
    """(account, debits, credits) in pence, sorted by account code."""
    totals: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for e in events:
        for ln in e.lines:
            totals[ln.account][0] += ln.debit
            totals[ln.account][1] += ln.credit
    return [(acct, dr, cr) for acct, (dr, cr) in sorted(totals.items())]


def _accounts(ws: Worksheet, events: Sequence[LedgerEvent]) -> None:
    tb = trial_balance(events)
    rows = [(a, pounds(dr), pounds(cr), pounds(dr - cr)) for a, dr, cr in tb]
    rows.append(("Total", pounds(sum(t[1] for t in tb)), pounds(sum(t[2] for t in tb)), pounds(sum(t[1] - t[2] for t in tb))))
    _table(ws, ("Account", "Debits £", "Credits £", "Balance £"), rows, money=(2, 3, 4), widths=(34, 14, 14, 14))
    ws.cell(row=ws.max_row, column=1).font = Font(bold=True)


def last_quarters(today: date, n: int = 4) -> list[tuple[date, date, str]]:
    """The last `n` complete calendar quarters, oldest first, as (start, end, period key)."""
    out: list[tuple[date, date, str]] = []
    year, q = today.year, (today.month - 1) // 3  # q = index of the current quarter (0-3)
    for _ in range(n):
        year, q = (year - 1, 3) if q == 0 else (year, q - 1)
        start = date(year, q * 3 + 1, 1)
        next_start = date(year, q * 3 + 4, 1) if q < 3 else date(year + 1, 1, 1)
        out.append((start, next_start - date.resolution, f"{year % 100:02d}A{q + 1}"))
    return out[::-1]


def _vat(ws: Worksheet, events: Sequence[LedgerEvent], today: date) -> None:
    returns = [compute_vat_return(list(events), key, s, e) for s, e, key in last_quarters(today)]
    header = ["Box", "What"] + [f"{r.period_key} ({r.start:%d/%m/%Y}–{r.end:%d/%m/%Y})" for r in returns]
    values = {
        1: [float(r.vat_due_sales) for r in returns], 2: [float(r.vat_due_acquisitions) for r in returns],
        3: [float(r.total_vat_due) for r in returns], 4: [float(r.vat_reclaimed) for r in returns],
        5: [float(r.net_vat_due) for r in returns], 6: [r.total_sales_ex_vat for r in returns],
        7: [r.total_purchases_ex_vat for r in returns], 8: [r.goods_supplied_ni_eu for r in returns],
        9: [r.acquisitions_ni_eu for r in returns],
    }
    rows = [(box, label, *values[box]) for box, label in VAT_BOXES]
    _table(ws, header, rows, widths=(6, 36, *([26] * len(returns))))
    for row in ws.iter_rows(min_row=2, min_col=3):
        for cell in row:
            cell.number_format = GBP if row[0].row <= 6 else WHOLE_GBP


def supplier_totals(events: Sequence[LedgerEvent]) -> list[tuple[str, int, int, int, int, date, date]]:
    """(supplier, entries, net, VAT, gross, first date, last date) in pence for approved purchases.

    A reversal of a purchase counts against the same supplier with the opposite sign. Gross is the
    entry's total debits (a balanced purchase debits net + VAT); net falls back to gross − VAT.
    """
    by_id = {e.id: e for e in events}
    totals: dict[str, list] = {}
    for e in events:
        original = by_id.get(e.reverses) if e.kind == "reversal" and e.reverses else None
        if e.kind != "purchase" and not (original and original.kind == "purchase"):
            continue
        sign = -1 if original else 1
        gross = sum(ln.debit for ln in e.lines)
        vat = e.vat or 0
        net = e.net if e.net is not None else gross - vat
        name = e.counterparty or (original.counterparty if original else None) or "(no supplier name)"
        t = totals.setdefault(name, [0, 0, 0, 0, e.date, e.date])
        t[0] += sign
        t[1] += sign * net
        t[2] += sign * vat
        t[3] += sign * gross
        t[4], t[5] = min(t[4], e.date), max(t[5], e.date)
    return [(name, *t) for name, t in sorted(totals.items(), key=lambda kv: (-kv[1][3], kv[0].lower()))]


def _suppliers(ws: Worksheet, events: Sequence[LedgerEvent]) -> None:
    st = supplier_totals(events)
    rows = [(n, c, pounds(net), pounds(vat), pounds(g), first, last) for n, c, net, vat, g, first, last in st]
    rows.append(("Total", sum(t[1] for t in st), pounds(sum(t[2] for t in st)), pounds(sum(t[3] for t in st)),
                 pounds(sum(t[4] for t in st)), None, None))
    header = ("Supplier", "Entries", "Net £", "VAT £", "Gross £", "First entry", "Last entry")
    _table(ws, header, rows, money=(3, 4, 5), dates=(6, 7), widths=(34, 9, 14, 14, 14, 12, 12))
    ws.cell(row=ws.max_row, column=1).font = Font(bold=True)


def _summary(ws: Worksheet, events: Sequence[LedgerEvent], bank_lines: Sequence[BankLine],
             proposals: Sequence[Proposal], generated: datetime) -> None:
    # A reversal counts against the kind of the entry it reverses, with the opposite sign (as on Suppliers and VAT).
    by_id = {e.id: e for e in events}
    signed: list[tuple[str, int, LedgerEvent]] = []
    for e in events:
        original = by_id.get(e.reverses) if e.kind == "reversal" and e.reverses else None
        signed.append((original.kind, -1, e) if original else (e.kind, 1, e))

    def kind_count(kind: str) -> int:
        return sum(sign for k, sign, _ in signed if k == kind)

    def kind_sum(kind: str, attr: str) -> int:
        return sum(sign * (getattr(e, attr) or 0) for k, sign, e in signed if k == kind)

    dates = [e.date for e in events]
    rows: list[tuple[str, object]] = [
        ("Generated at", generated.replace(tzinfo=None)),
        ("Entries posted", len(events)),
        ("First entry", min(dates) if dates else None),
        ("Last entry", max(dates) if dates else None),
        ("Total debits £", pounds(sum(ln.debit for e in events for ln in e.lines))),
        ("Total credits £", pounds(sum(ln.credit for e in events for ln in e.lines))),
        ("Sales entries", kind_count("sale")),
        ("Sales net £", pounds(kind_sum("sale", "net"))),
        ("VAT on sales £", pounds(kind_sum("sale", "vat"))),
        ("Purchase entries", kind_count("purchase")),
        ("Purchases net £", pounds(kind_sum("purchase", "net"))),
        ("VAT on purchases £", pounds(kind_sum("purchase", "vat"))),
        ("Suppliers", len(supplier_totals(events))),
        ("Bank lines", len(bank_lines)),
        ("Bank lines matched", sum(ln.status == "matched" for ln in bank_lines)),
        ("Bank lines unmatched", sum(ln.status == "unmatched" for ln in bank_lines)),
        ("Proposals waiting", len(proposals)),
    ]
    _table(ws, ("Measure", "Value"), rows, widths=(28, 18))
    for (label, cell) in ws.iter_rows(min_row=2, max_col=2):
        if label.value.endswith("£"):
            cell.number_format = GBP
        elif label.value in ("First entry", "Last entry"):
            cell.number_format = DATE
        elif label.value == "Generated at":
            cell.number_format = "dd/mm/yyyy hh:mm"


def _bank(ws: Worksheet, lines: Sequence[BankLine]) -> None:
    rows = (
        (ln.date, ln.description, ln.reference, pounds(ln.amount_pence), pounds(ln.balance_pence), ln.status,
         ", ".join(ln.event_ids()) or None, ln.source_file)
        for ln in lines
    )
    header = ("Date", "Description", "Reference", "Amount £", "Balance £", "Status", "Matched event", "Statement")
    _table(ws, header, rows, money=(4, 5), dates=(1,), widths=(12, 40, 18, 12, 12, 11, 34, 50))


def _proposals(ws: Worksheet, proposals: Sequence[Proposal]) -> None:
    rows = (
        (p.created_at.replace(tzinfo=None) if p.created_at else None, p.id, p.status, p.extracted.supplier_name,
         p.extracted.date, p.extracted.gross_total, p.extracted.category_guess, "; ".join(p.reasons) or None, p.file_path)
        for p in proposals
    )
    header = ("Received", "Proposal id", "Status", "Supplier", "Document date", "Gross £", "Category", "Reasons", "File")
    _table(ws, header, rows, money=(6,), dates=(1,), widths=(12, 34, 13, 28, 13, 12, 24, 50, 60))


def _vehicles(ws: Worksheet, mileage: MileageSummary | None) -> None:
    ty = mileage.tax_year if mileage else ""
    rows: list[Sequence[object]] = [
        (v.name, v.registration, v.kind, v.owned_by, "yes" if v.active else "no", v.miles, v.journeys,
         pounds(v.allowance_pence) if v.owned_by == "personal" else None,
         pounds(v.cost_pence) if v.owned_by == "business" else None, v.cost_entries or None,
         pounds(v.pence_per_mile))
        for v in (mileage.vehicles if mileage else [])
    ]
    if mileage:
        rows.append(("Total", None, None, None, None, sum(v.miles for v in mileage.vehicles),
                     sum(v.journeys for v in mileage.vehicles), pounds(mileage.allowance_pence),
                     pounds(sum(v.cost_pence for v in mileage.vehicles)), None, None))
    header = ("Vehicle", "Registration", "Kind", "Owned by", "Active", f"Business miles {ty}".strip(), "Journeys",
              "Mileage allowance £", "Tagged costs £", "Receipts", "Per business mile £")
    _table(ws, header, rows, money=(8, 9, 11), widths=(24, 13, 11, 10, 8, 20, 9, 19, 15, 9, 19))
    if mileage:
        ws.cell(row=ws.max_row, column=1).font = Font(bold=True)
        crossed = f"{mileage.threshold_crossed_on:%d/%m/%Y}" if mileage.threshold_crossed_on else "not yet"
        ws.append([])
        ws.append([f"Cars and vans passed {mileage.threshold_miles:,} business miles: {crossed}. "
                   "Allowance at HMRC approved mileage rates, computed by code from _System/Mileage."])
        for note in mileage.notes:
            ws.append([note])


def build_books_xlsx(
    events: Sequence[LedgerEvent], bank_lines: Sequence[BankLine], proposals: Sequence[Proposal],
    generated: datetime | None = None, mileage: MileageSummary | None = None,
) -> bytes:
    """The whole workbook as .xlsx bytes."""
    generated = generated or datetime.now(UTC)
    wb = Workbook()
    sheets = {name: (wb.active if i == 0 else wb.create_sheet()) for i, name in enumerate(SHEETS)}
    for name, ws in sheets.items():
        ws.title = name
    _read_me(sheets["README"], generated)
    _summary(sheets["Summary"], events, bank_lines, proposals, generated)
    _ledger(sheets["Ledger"], events)
    _accounts(sheets["Accounts"], events)
    _vat(sheets["VAT"], events, generated.date())
    _suppliers(sheets["Suppliers"], events)
    _bank(sheets["Bank"], bank_lines)
    _proposals(sheets["Proposals"], proposals)
    _vehicles(sheets["Vehicles"], mileage)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
