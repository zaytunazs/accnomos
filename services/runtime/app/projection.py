def _jobs(ws: Worksheet, jobs: Sequence[JobSummary]) -> None:
    """Margin = billable value of the hours − labour cost − materials (app/jobs.py summarise)."""
    rows: list[tuple[object, ...]] = [
        (
            s.job.name,
            s.customer_name or s.job.customer_id,
            s.job.status,
            s.hours,
            pounds(s.labour_cost_pence),
            pounds(s.materials_pence),
            pounds(s.billable_value_pence),
            pounds(s.invoiced_value_pence),
            pounds(s.margin_pence),
        )
        for s in jobs
    ]
    rows.append(
        (
            "Total",
            None,
            None,
            sum(s.hours for s in jobs),
            *(
                pounds(sum(getattr(s, f) for s in jobs))
                for f in (
                    "labour_cost_pence",
                    "materials_pence",
                    "billable_value_pence",
                    "invoiced_value_pence",
                    "margin_pence",
                )
            ),
        )
    )
    header = (
        "Job",
        "Customer",
        "Status",
        "Hours",
        "Labour cost £",
        "Materials £",
        "Billable value £",
        "Invoiced £",
        "Margin £",
    )
    _table(ws, header, rows, money=(5, 6, 7, 8, 9), widths=(34, 28, 9, 9, 14, 14, 16, 14, 14))
    ws.cell(row=ws.max_row, column=1).font = Font(bold=True)


def _vehicles(ws: Worksheet, mileage: MileageSummary | None) -> None:
    ty = mileage.tax_year if mileage else ""
    rows: list[Sequence[object]] = [
        (
            v.name,
            v.registration,
            v.kind,
            v.owned_by,
            "yes" if v.active else "no",
            v.miles,
            v.journeys,
            pounds(v.allowance_pence) if v.owned_by == "personal" else None,
            pounds(v.cost_pence) if v.owned_by == "business" else None,
            v.cost_entries or None,
            pounds(v.pence_per_mile),
        )
        for v in (mileage.vehicles if mileage else [])
    ]
    if mileage:
        rows.append(
            (
                "Total",
                None,
                None,
                None,
                None,
                sum(v.miles for v in mileage.vehicles),
                sum(v.journeys for v in mileage.vehicles),
                pounds(mileage.allowance_pence),
                pounds(sum(v.cost_pence for v in mileage.vehicles)),
                None,
                None,
            )
        )
    header = (
        "Vehicle",
        "Registration",
        "Kind",
        "Owned by",
        "Active",
        f"Business miles {ty}".strip(),
        "Journeys",
        "Mileage allowance £",
        "Tagged costs £",
        "Receipts",
        "Per business mile £",
    )
    _table(ws, header, rows, money=(8, 9, 11), widths=(24, 13, 11, 10, 8, 20, 9, 19, 15, 9, 19))
    if mileage:
        ws.cell(row=ws.max_row, column=1).font = Font(bold=True)
        crossed = f"{mileage.threshold_crossed_on:%d/%m/%Y}" if mileage.threshold_crossed_on else "not yet"
        ws.append([])
        ws.append(
            [
                f"Cars and vans passed {mileage.threshold_miles:,} business miles: {crossed}. "
                "Allowance at HMRC approved mileage rates, computed by code from _System/Mileage."
            ]
        )
        for note in mileage.notes:
            ws.append([note])


def _payroll(ws: Worksheet, runs: Sequence[PayRun], names: dict[str, tuple[str, str]]) -> None:
    """One row per person per pay run, newest first. Deductions are estimates (app/payroll.py)."""
    rows: list[Sequence[object]] = []
    for run in runs:
        actual = [
            pounds(run.confirmed_gross_pence),
            pounds(run.confirmed_er_ni_pence),
        ]  # once per run, on its first row
        if not run.lines:
            rows.append((run.period, run.pay_date, run.status, "(no lines)", *([None] * 7), *actual))
        for i, ln in enumerate(run.lines):
            rows.append(
                (
                    run.period,
                    run.pay_date,
                    run.status,
                    names.get(ln.staff_id, (ln.staff_id, ""))[0],
                    ln.hours,
                    pounds(ln.rate_pence),
                    pounds(ln.gross_pence),
                    pounds(ln.est_paye_pence),
                    pounds(ln.est_ee_ni_pence),
                    pounds(ln.est_net_pence),
                    pounds(ln.est_er_ni_pence),
                    *(actual if i == 0 else [None, None]),
                )
            )
    header = (
        "Period",
        "Pay date",
        "Status",
        "Employee",
        "Hours",
        "Rate £",
        "Gross £",
        "Est. PAYE £",
        "Est. employee NI £",
        "Est. net £",
        "Est. employer NI £",
        "Actual gross (run) £",
        "Actual employer NI (run) £",
    )
    _table(ws, header, rows, money=range(6, 14), dates=(2,), widths=(9, 12, 10, 26, 8, 10, 12, 12, 18, 12, 18, 20, 24))
    ws.append([])
    ws.append([R.ESTIMATE_LABEL])
    ws.cell(row=ws.max_row, column=1).font = Font(bold=True)
    for limit in R.LIMITS:
        ws.append([limit])


def build_books_xlsx(
    events: Sequence[LedgerEvent],
    bank_lines: Sequence[BankLine],
    proposals: Sequence[Proposal],
    generated: datetime | None = None,
    *,
    jobs: Sequence[JobSummary] = (),
    contacts: Sequence[Contact] | None = None,
    ledger: Ledger | None = None,
    mileage: MileageSummary | None = None,
    payroll: Sequence[PayRun] = (),
    staff_names: dict[str, tuple[str, str]] | None = None,
) -> bytes:
    """The whole workbook as .xlsx bytes. Without `contacts`, the contact book is derived from the events alone."""
    generated = generated or datetime.now(UTC)
    ledger = ledger or Ledger(events=list(events), bank_lines=[ln for ln in bank_lines if ln.status == "matched"])
    contacts = merge_ledger([], ledger, generated) if contacts is None else contacts
    today = generated.date()
    year_start = uk_tax_year_start(today)
    wb = Workbook()
    first = wb.active
    if not isinstance(first, Worksheet):  # a new Workbook always starts with one worksheet
        raise RuntimeError("openpyxl Workbook() has no first worksheet")
    sheets = {name: (first if i == 0 else wb.create_sheet()) for i, name in enumerate(SHEETS)}
    for name, ws in sheets.items():
        ws.title = name
    _read_me(sheets["README"], generated)
    customer_rows = contact_sheet_rows(contacts, ledger, "sale", year_start, today)
    supplier_rows = contact_sheet_rows(contacts, ledger, "purchase", year_start, today)
    _summary(sheets["Summary"], events, bank_lines, proposals, generated, len(customer_rows), len(supplier_rows))
    _ledger(sheets["Ledger"], events)
    _accounts(sheets["Accounts"], events)
    _vat(sheets["VAT"], events, generated.date())
    _pl(sheets["P&L"], events, today)
    _contacts_sheet(sheets["Customers"], "Customer", "Unpaid by them £", customer_rows)
    _contacts_sheet(sheets["Suppliers"], "Supplier", "Unpaid by you £", supplier_rows)
    _bank(sheets["Bank"], bank_lines)
    _proposals(sheets["Proposals"], proposals)
    _jobs(sheets["Jobs"], jobs)
    _vehicles(sheets["Vehicles"], mileage)
    _payroll(sheets["Payroll"], payroll, staff_names or {})
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
