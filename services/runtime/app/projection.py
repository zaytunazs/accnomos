def pounds(pence: int | None) -> float | None:
    return None if pence is None else pence / 100


_NUMBERISH = re.compile(r"^[+-]?[\d.,]+$")  # a negative number stored as text is fine


def _safe_text(v: object) -> object:
    """openpyxl writes any string starting with = as a formula;
    text from receipts, names and notes must never be one. Tab and carriage return too (OWASP): a spreadsheet
    opening the CSV export may drop them and read what follows as a formula.
    """
    if isinstance(v, str) and v[:1] in ("=", "+", "-", "@", "\t", "\r") and not _NUMBERISH.match(v):
        return "'" + v
    return v


def _table(
    ws: Worksheet,
    header: Sequence[str],
    rows: Iterable[Sequence[object]],
    money: Sequence[int] = (),
    dates: Sequence[int] = (),
    widths: Sequence[int] = (),
) -> None:
    """Bold header, frozen below it, money/date number formats on the given (1-based) columns."""
    ws.append(list(header))
    for cell in ws[1]:
        cell.font = Font(bold=True)
    for row in rows:
        ws.append([_safe_text(v) for v in row])
    for col in money:
        for (cell,) in ws.iter_rows(min_row=2, min_col=col, max_col=col):
            cell.number_format = GBP
    for col in dates:
        for (cell,) in ws.iter_rows(min_row=2, min_col=col, max_col=col):
            cell.number_format = DATE
    for i, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = width
    ws.freeze_panes = "A2"


